"""Builds the final Ranklit kit from gen.py geometry: brand SVGs, favicon, and the React component."""
# Run: python3 scripts/brand/kit.py [--active folded-map|lit-r]   (then re-render src/app/apple-icon.png, see BRAND.md)
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import *
PROJ = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
B = f"{PROJ}/public/brand"; os.makedirs(B, exist_ok=True)

def wm_svg(ink, acc, title="Ranklit"):
    body, w = wordmark(ink, acc)
    return svg(w + 16, 224, f'<g transform="translate(8 0)">{body}</g>', title), w + 16

from gen_alt import folded_map
import argparse
ap = argparse.ArgumentParser(description="Build the Ranklit logo kit. Every family is always written to public/brand/<family>/; --active also becomes the site logo.")
ap.add_argument("--active", choices=["folded-map", "lit-r"], default="folded-map")
ACTIVE = ap.parse_args().active

# One adapter per symbol family: S(fg, acc, tile, edge, border) -> svg body. APP = offset for the full-bleed app icon.
FAMILIES = {
    "lit-r": (lambda fg=INK, acc=PURPLE, tile=True, edge=INK, border=12: sym_B(fg=fg, dot=acc, tile=LIME if tile else None, edge=edge, border=border), (12, 8)),
    "folded-map": (lambda fg=INK, acc=PURPLE, tile=True, edge=INK, border=12: folded_map(fg=fg, acc=acc, with_tile=tile, edge=edge, border=border), (0, -8)),
}

def lockup_for(S, wm_ink, wm_dot, **sym):
    body, w = wordmark(wm_ink, wm_dot)
    k = 0.92  # wordmark x-height matches the symbol's optical centre, baseline-aligned
    return svg(256 + 40 + w * k, 256, f'{S(**sym)}<g transform="translate(296 {f(118 - 100 * k + 24)}) scale({k})">{body}</g>', "Ranklit")

def kit(name):
    S, (ax, ay) = FAMILIES[name]
    return {
        "ranklit-symbol.svg": svg(256, 256, S(), "Ranklit"),
        "ranklit-symbol-ink.svg": svg(256, 256, S(fg=INK, acc=INK, tile=False), "Ranklit"),
        "ranklit-symbol-white.svg": svg(256, 256, S(fg=WHITE, acc=WHITE, tile=False), "Ranklit"),
        "ranklit-symbol-small.svg": svg(256, 256, S(border=20), "Ranklit"),
        "ranklit-wordmark.svg": wm_svg(INK, PURPLE)[0],
        "ranklit-wordmark-ink.svg": wm_svg(INK, INK)[0],
        "ranklit-wordmark-white.svg": wm_svg(WHITE, LIME)[0],
        "ranklit-lockup.svg": lockup_for(S, INK, PURPLE),
        "ranklit-lockup-ink.svg": lockup_for(S, INK, INK, fg=INK, acc=INK, tile=False),
        "ranklit-lockup-white.svg": lockup_for(S, WHITE, LIME, edge=WHITE),
        # app icon: full-bleed tile, the OS applies its own corner mask
        "ranklit-app-icon.svg": svg(256, 256, f'<rect width="256" height="256" fill="{LIME}"/><g transform="translate({ax} {ay})">{S(tile=False)}</g>', "Ranklit"),
    }

for name in FAMILIES:
    d = f"{B}/{name}"; os.makedirs(d, exist_ok=True)
    for n, c in kit(name).items(): open(f"{d}/{n}", "w").write(c)
files = kit(ACTIVE)
for n, c in files.items(): open(f"{B}/{n}", "w").write(c)
open(f"{PROJ}/src/app/icon.svg", "w").write(files["ranklit-symbol-small.svg"])
S_active = FAMILIES[ACTIVE][0]

# ---- React component, generated so code and brand files never drift ----
def paths(svgstr):  # inner markup minus the svg/title wrapper
    return re.sub(r'^<svg[^>]*><title[^>]*>[^<]*</title>|</svg>\n$', "", svgstr)
sym_inner = paths(svg(256, 256, S_active(), ""))
wm_body, wm_w = wordmark("currentColor", "var(--logo-dot)")
jsx = lambda m: m.replace("fill-rule", "fillRule")
open(f"{PROJ}/src/components/logo.tsx", "w").write(f'''// GENERATED by scripts/brand/kit.py (see BRAND.md). Edit the generator, not this file.
import Link from "next/link";
import clsx from "clsx";
import type {{ CSSProperties }} from "react";

/** The active Ranklit symbol ({ACTIVE}) on its sticker tile. Decorative: pair with a text label. */
export function LogoMark({{ className = "size-8" }}: {{ className?: string }}) {{
  return (
    <svg viewBox="0 0 256 256" className={{className}} aria-hidden>
      {jsx(sym_inner)}
    </svg>
  );
}}

/** Custom-drawn wordmark (outlined shapes, no font). Inherits text colour; the i-dot is the lit spot. */
export function Wordmark({{ className, dark }}: {{ className?: string; dark?: boolean }}) {{
  return (
    <svg
      viewBox="0 0 {f(wm_w)} 224"
      className={{clsx("h-[1em] w-auto", dark ? "text-white" : "text-ink", className)}}
      style={{{{ "--logo-dot": dark ? "#c6f432" : "#9b47cc" }} as CSSProperties}}
      aria-hidden
    >
      {jsx(wm_body)}
    </svg>
  );
}}

export function Logo({{ dark, className }}: {{ dark?: boolean; className?: string }}) {{
  return (
    <Link href="/" className={{clsx("flex min-h-11 items-center gap-2", className)}} aria-label="Ranklit home">
      <LogoMark className="size-9 transition-transform duration-300 ease-[var(--ease-spring)] hover:-rotate-6" />
      <Wordmark dark={{dark}} className="mt-1 text-[26px]" />
    </Link>
  );
}}
''')
print("active:", ACTIVE, "| families:", ", ".join(FAMILIES))
